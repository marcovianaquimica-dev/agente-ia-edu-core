def _merge() -> dict[str, dict[str, int]]:
    """V1 + adjudicados. Recusa qualquer alteracao de grau existente."""
    saida = {query: dict(graus) for query, graus in VECTOR_QRELS_V1.items()}
    for registro in ADJUDICATION_LOG:
        if registro["grade"] == 0:
            continue
        query = str(registro["query"])
        text_hash = str(registro["text_hash"])
        anterior = VECTOR_QRELS_V1.get(query, {}).get(text_hash)
        if anterior is not None:
            raise ValueError(
                f"adjudicacao tentou alterar grau da V1: {query} / {text_hash}"
            )
        saida.setdefault(query, {})[text_hash] = int(registro["grade"])
    return saida


VECTOR_QRELS_V2: dict[str, dict[str, int]] = _merge()


def relevant_v2(query: str, minimum: int = 1) -> frozenset[str]:
    """Hashes com grau >= ``minimum`` na regua adjudicada."""
    return frozenset(
        text_hash
        for text_hash, grau in VECTOR_QRELS_V2.get(query, {}).items()
        if grau >= minimum
    )
